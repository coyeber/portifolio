-- Modelo: uma pessoa tem N formacoes, N experiencias e N projetos.
-- Pessoas e habilidades possuem relacao N:N pela tabela pessoa_habilidades.

CREATE TABLE IF NOT EXISTS pessoas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  telefone VARCHAR(30),
  cidade VARCHAR(120),
  resumo TEXT
);

CREATE TABLE IF NOT EXISTS formacoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pessoa_id INTEGER NOT NULL REFERENCES pessoas(id) ON DELETE CASCADE,
  curso VARCHAR(160) NOT NULL,
  instituicao VARCHAR(160) NOT NULL,
  inicio DATE,
  fim DATE,
  situacao VARCHAR(60),
  CONSTRAINT formacoes_periodo CHECK (fim IS NULL OR inicio IS NULL OR fim >= inicio)
);

CREATE TABLE IF NOT EXISTS experiencias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pessoa_id INTEGER NOT NULL REFERENCES pessoas(id) ON DELETE CASCADE,
  empresa VARCHAR(160) NOT NULL,
  cargo VARCHAR(160) NOT NULL,
  inicio DATE,
  fim DATE,
  descricao TEXT,
  CONSTRAINT experiencias_periodo CHECK (fim IS NULL OR inicio IS NULL OR fim >= inicio)
);

CREATE TABLE IF NOT EXISTS projetos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pessoa_id INTEGER NOT NULL REFERENCES pessoas(id) ON DELETE CASCADE,
  nome VARCHAR(160) NOT NULL,
  descricao TEXT,
  url TEXT
);

CREATE TABLE IF NOT EXISTS habilidades (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE,
  categoria VARCHAR(120)
);

CREATE TABLE IF NOT EXISTS pessoa_habilidades (
  pessoa_id INTEGER NOT NULL REFERENCES pessoas(id) ON DELETE CASCADE,
  habilidade_id INTEGER NOT NULL REFERENCES habilidades(id) ON DELETE CASCADE,
  nivel VARCHAR(25) NOT NULL CHECK (nivel IN ('Basico', 'Intermediario', 'Avancado')),
  PRIMARY KEY (pessoa_id, habilidade_id)
);

CREATE INDEX IF NOT EXISTS idx_formacoes_pessoa ON formacoes(pessoa_id);
CREATE INDEX IF NOT EXISTS idx_experiencias_pessoa ON experiencias(pessoa_id);
CREATE INDEX IF NOT EXISTS idx_projetos_pessoa ON projetos(pessoa_id);
CREATE INDEX IF NOT EXISTS idx_pessoa_habilidades_habilidade ON pessoa_habilidades(habilidade_id);
